export interface GenericToContractedHoursPreview {
  source: ShiftCountPreference;
  replacementDraft: ContractedHoursDraft;
  changes: ContractedHoursConversionField[];
}

export function previewGenericToContractedHours(
  preference: ShiftCountPreference,
  target: ContractedHoursTargetInput,
  scenario: ContractedHoursScenario,
  options: { deriveCoefficients?: boolean } = {},
): ContractedHoursResult<GenericToContractedHoursPreview> {
  const draft = buildContractedHoursDraft(
    {
      ...(preference.description !== undefined
        ? { description: preference.description }
        : {}),
      person: preference.person,
      countDates: preference.countDates,
      countShiftTypes: preference.countShiftTypes,
      target,
      existingCoefficients: preference.countShiftTypeCoefficients,
      deriveCoefficients: options.deriveCoefficients === true,
    },
    scenario,
  );
  if (!draft.ok) {
    return draft;
  }

  const changes: ContractedHoursConversionField[] = [
    { field: "hoursContract", before: preference.hoursContract, after: draft.value.hoursContract },
    { field: "expression", before: preference.expression, after: draft.value.expression },
    { field: "target", before: preference.target, after: draft.value.target },
    { field: "weight", before: preference.weight, after: draft.value.weight },
    {
      field: "countShiftTypeCoefficients",
      before: preference.countShiftTypeCoefficients,
      after: draft.value.countShiftTypeCoefficients,
    },
  ];
  return {
    ok: true,
    value: {
      source: structuredClone(preference),
      replacementDraft: draft.value,
      changes,
    },
  };
}

export function confirmGenericToContractedHours(
  preview: GenericToContractedHoursPreview,
): ContractedHoursResult<ContractedHoursPreference> {
  const missing = preview.replacementDraft.countShiftTypeCoefficients.find(
    ([, value]) => value === "",
  );
  if (missing) {
    return failure(
      "non_derivable_coefficient",
      `Shift type '${missing[0]}' requires an explicit positive integer coefficient.`,
      `countShiftTypeCoefficients.${missing[0]}`,
    );
  }
  return {
    ok: true,
    value: structuredClone(preview.replacementDraft) as ContractedHoursPreference,
  };
}

export function convertContractedHoursToGeneric(
  preference: ContractedHoursPreference,
): ShiftCountPreference {
  const generic = structuredClone(preference) as ShiftCountPreference;
  delete generic.hoursContract;
  return generic;
}

export type ContractedHoursLeaveCreditOutcome =
  | { status: "not-applicable" }
  | { status: "unknown"; error: ContractedHoursError }
  | { status: "credited"; expansion: ContractedHoursExpansion }
  | { status: "uncredited"; expansion: ContractedHoursExpansion };

export function getContractedHoursLeaveCreditOutcome(
  scenario: ContractedHoursScenario,
  preference: ShiftCountPreference,
): ContractedHoursLeaveCreditOutcome {
  if (!preference.hoursContract) {
    return { status: "not-applicable" };
  }
  const expansion = expandContractedHoursShiftTypes(
    scenario.shiftTypes,
    preference.countShiftTypes,
  );
  if (!expansion.ok) {
    return { status: "unknown", error: expansion.error };
  }
  return expansion.value.semanticIds.includes(LEAVE)
    ? { status: "credited", expansion: expansion.value }
    : { status: "uncredited", expansion: expansion.value };
}
